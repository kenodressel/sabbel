import Foundation

/// Paste transcribed text into the focused app. Port of `sabbel/injector.py`.
///
/// Every AppKit / Accessibility / Quartz call lives behind `PasteEnvironment`
/// (the real adapter is `SystemPasteEnvironment` in the app target), so the
/// decision logic and the clipboard save/restore contract here are testable with
/// a scripted fake.

/// The caller needs the reason, not just success/failure: "text is in your
/// clipboard" is an actively wrong thing to tell someone whose transcript was
/// withheld from a password field.
public enum InjectOutcome: String, Sendable {
    /// Pasted, clipboard restored.
    case pasted
    /// No text field — text left in the clipboard for a manual paste.
    case leftInClipboard
    /// The target app is no longer frontmost — text left in the clipboard for a manual paste.
    case focusChanged
    /// Password field — nothing pasted, nothing copied.
    case refusedSecure
}

/// The app that should receive the transcription.
///
/// Captured when recording *starts*, not when it finishes: transcription takes
/// seconds and the user often switches windows while it runs. Without this the
/// text lands in whatever happens to be focused at paste time.
public struct FocusTarget: Equatable, Sendable {
    public let pid: Int32
    public let name: String?
    /// The app's bundle identifier, for per-app text rules.
    public let bundleID: String?

    public init(pid: Int32, name: String?, bundleID: String? = nil) {
        self.pid = pid
        self.name = name
        self.bundleID = bundleID
    }
}

/// What the Accessibility API tells us about the focused UI element.
public struct FocusedElement: Equatable, Sendable {
    /// `AXRole`, nil when unreadable.
    public var role: String?
    /// `AXSubrole`, nil when unreadable.
    public var subrole: String?
    /// `AXSelectedTextRange` is readable (the element has a cursor).
    public var hasSelectedTextRange: Bool
    /// `AXValue` is settable.
    public var valueSettable: Bool
    /// `AXSelectedText` is settable.
    public var selectedTextSettable: Bool

    public init(role: String?, subrole: String?, hasSelectedTextRange: Bool,
                valueSettable: Bool, selectedTextSettable: Bool) {
        self.role = role
        self.subrole = subrole
        self.hasSelectedTextRange = hasSelectedTextRange
        self.valueSettable = valueSettable
        self.selectedTextSettable = selectedTextSettable
    }
}

/// One type of a pasteboard item with its data.
public struct PasteboardFlavor: Equatable, Sendable {
    public var type: String
    public var data: Data

    public init(_ type: String, _ data: Data) {
        self.type = type
        self.data = data
    }
}

public extension Array where Element == PasteboardFlavor {
    /// The data of the first flavour of `type`.
    func data(for type: String) -> Data? { first { $0.type == type }?.data }
}

/// Every item and every type on the pasteboard.
///
/// Saving only the string flavour (the old behaviour) destroys images, rich text
/// and file references: whatever the user had copied comes back as plain text,
/// or not at all.
///
/// Each item keeps its types in their original order. That order is fidelity
/// order, richest first, and a receiving app pastes the first type it
/// understands: a dictionary would shuffle it and could turn rich text into
/// plain text on restore.
public struct ClipboardSnapshot: Equatable, Sendable {
    public var items: [[PasteboardFlavor]]

    public init(items: [[PasteboardFlavor]]) { self.items = items }
}

/// The system side of pasting. Implemented on AppKit/AX/Quartz by the app, and
/// by a scripted fake in tests.
public protocol PasteEnvironment: Sendable {
    /// pid of the frontmost app, nil when it can't be read.
    func frontmostPID() -> Int32?
    /// The frontmost app's focused element, nil when it can't be read (Electron apps, etc.).
    func focusedElement() -> FocusedElement?
    /// `AXValue` of the focused element, nil when unreadable.
    func focusedValue() -> String?
    /// Whether Command, Control, Option, Shift or Fn is physically held,
    /// independent of events we synthesise.
    func modifiersHeld() -> Bool
    func captureClipboard() -> ClipboardSnapshot
    /// Clear the pasteboard and rewrite `snapshot` (an empty snapshot just clears).
    func restoreClipboard(_ snapshot: ClipboardSnapshot)
    /// Put `text` on the pasteboard tagged `org.nspasteboard.TransientType` and
    /// `org.nspasteboard.AutoGeneratedType`, so clipboard managers (Maccy, Paste,
    /// etc.) ignore it. See http://nspasteboard.org/
    ///
    /// ConcealedType is deliberately NOT set: it means "password", which would be
    /// a lie for a dictation transcript and would hide it from the user's own history.
    ///
    /// Returns the resulting change count.
    func writeTransient(_ text: String) -> Int
    func clipboardChangeCount() -> Int
    /// The pasteboard's plain-text string, if any.
    func clipboardString() -> String?
    /// Synthesise Cmd+V.
    ///
    /// When the target pid is known (captured at record start) the events go
    /// straight to it. A session-wide post lands wherever focus happens to be by
    /// the time the event is delivered, which is not necessarily where the user
    /// was speaking.
    func postCommandV(to pid: Int32?)
    /// Synthesise the Return key (down and up), posted like `postCommandV`.
    func postReturn(to pid: Int32?)
    func sleep(_ seconds: TimeInterval)
    /// A monotonic clock.
    func now() -> TimeInterval
}

public struct Injector: Sendable {
    /// Roles where we KNOW paste won't work (no text input).
    static let nonTextRoles: Set<String> = [
        "AXWebArea", "AXImage", "AXGroup", "AXToolbar", "AXMenuBar",
        "AXScrollArea", "AXSplitGroup", "AXTable", "AXOutline",
    ]

    static let modifierPoll: TimeInterval = 0.015
    static let verifyPoll: TimeInterval = 0.02

    let env: any PasteEnvironment
    let prePasteDelay: TimeInterval
    let postPasteDelay: TimeInterval
    let modifierTimeout: TimeInterval
    let verifyTimeout: TimeInterval
    let log: (@Sendable (String) -> Void)?
    /// Sabbel's own pid. Sabbel is never a paste destination.
    let ownPID: Int32?

    /// - Parameter ownPID: Sabbel's own pid; when Sabbel is frontmost at paste
    ///   time the text is left in the clipboard instead of pasted into nothing.
    ///   Nil disables the check.
    /// - Parameter log: receives the same INFO-level decisions `injector.py` logs
    ///   (focus changed, secure field, non-text role, modifier timeout, paste not
    ///   observed, clipboard changed during the paste). Nil drops them.
    public init(env: any PasteEnvironment, prePasteDelay: TimeInterval = 0.05, postPasteDelay: TimeInterval = 0.15,
                modifierTimeout: TimeInterval = 2.0, verifyTimeout: TimeInterval = 1.0,
                ownPID: Int32? = nil, log: (@Sendable (String) -> Void)? = nil) {
        self.env = env
        self.ownPID = ownPID
        self.prePasteDelay = prePasteDelay
        self.postPasteDelay = postPasteDelay
        self.modifierTimeout = modifierTimeout
        self.verifyTimeout = verifyTimeout
        self.log = log
    }

    private func info(_ message: String) { log?(message) }

    private static func describe(_ target: FocusTarget?) -> String {
        guard let target else { return "nil" }
        return target.name ?? "pid \(target.pid)"
    }

    // MARK: main entry point

    /// Paste text into the focused app via the clipboard and a synthetic Cmd+V.
    ///
    /// If a text input is detected (or detection is inconclusive), pastes and
    /// restores the previous clipboard. If we're confident there's no text input,
    /// pastes and leaves the transcribed text in the clipboard as a fallback.
    ///
    /// Focus is checked twice: at the start, and again immediately before Cmd+V,
    /// because the modifier wait and the pre-paste delay give the user time to
    /// switch apps. Either mismatch leaves the text in the clipboard, unpasted.
    public func inject(_ text: String, target: FocusTarget?) -> InjectOutcome {
        if !focusTargetIsActive(target) {
            info("Focus changed since recording started (expected \(Self.describe(target))) — leaving text in clipboard")
            _ = env.writeTransient(text)
            return .focusChanged
        }
        if sabbelIsFrontmost() {
            info("Sabbel itself is frontmost — leaving text in clipboard")
            _ = env.writeTransient(text)
            return .leftInClipboard
        }

        let focused = env.focusedElement()
        if Self.isSecure(focused) {
            info("Focused element is a secure text field — refusing to paste")
            return .refusedSecure
        }

        let pasteLikely = Self.canAcceptPaste(focused)
        if !pasteLikely {
            // canAcceptPaste only says no for a known non-text role.
            info("Paste detection: non-text role \(focused?.role ?? "nil") — text left in clipboard")
        }

        // Don't let a still-held Option turn our Cmd+V into Cmd+Opt+V.
        waitForModifiersReleased(timeout: modifierTimeout)

        let snapshot = env.captureClipboard()
        let valueBefore = env.focusedValue()
        let ourChangeCount = env.writeTransient(text)

        // Wait for pasteboard sync
        env.sleep(prePasteDelay)

        // Second focus check, as late as possible: the modifier wait can take up
        // to `modifierTimeout`, and a Cmd+V posted to a pid that is no longer
        // frontmost may land nowhere or somewhere the user isn't looking. The
        // transcript stays in the clipboard (no restore) so it can be pasted by hand.
        if !focusTargetIsActive(target) {
            info("Focus lost right before Cmd+V (expected \(Self.describe(target))) — leaving text in clipboard")
            return .focusChanged
        }
        if sabbelIsFrontmost() {
            info("Sabbel itself is frontmost right before Cmd+V — leaving text in clipboard")
            return .leftInClipboard
        }

        // The pid check can't see a focus move *within* the target app (Tab into a
        // password field, a login sheet appearing) during the same window, so the
        // secure check is repeated too. A refused secure take is never pasted,
        // copied or saved: put the user's clipboard back so the transcript doesn't
        // sit there.
        if Self.isSecure(env.focusedElement()) {
            info("Focused element is a secure text field — refusing to paste")
            env.restoreClipboard(snapshot)
            return .refusedSecure
        }

        env.postCommandV(to: target?.pid)

        // Wait for the paste to actually land before touching the clipboard again.
        // A fixed 150ms is not enough for Slack/Ghostty/Electron; restoring too
        // early makes the app paste the *previous* clipboard contents instead.
        //
        // Only poll when the field is actually readable. Electron apps and
        // terminals expose no AXValue, so polling them would burn the full
        // verifyTimeout on every single dictation — far worse than the fixed
        // delay it replaced.
        if valueBefore == nil {
            env.sleep(postPasteDelay)
        } else {
            let deadline = env.now() + verifyTimeout
            var observed = false
            while env.now() < deadline {
                if pasteObserved(before: valueBefore, expected: text) {
                    observed = true
                    break
                }
                env.sleep(Self.verifyPoll)
            }
            if !observed {
                info("Paste not observed within \(String(format: "%.1f", verifyTimeout))s — restoring anyway")
            }
            // Not observing the paste is not evidence that it failed — plenty of
            // apps simply never report it. Waiting out the timeout already gave the
            // target far longer than the old fixed delay, so restore as usual
            // rather than telling the user something untrue.
        }

        // Did someone else touch the clipboard while we were pasting? (The user
        // copied something, or another app wrote to it.)
        if env.clipboardChangeCount() != ourChangeCount {
            if env.clipboardString() != text {
                info("Clipboard changed during paste — skipping restore")
                return .pasted
            }
        }

        if !pasteLikely {
            // Leave text in clipboard as fallback
            return .leftInClipboard
        }

        env.restoreClipboard(snapshot)
        return .pasted
    }

    // MARK: Return key

    /// Presses Return in `target` after `settle` seconds (time for the app to
    /// insert pasted text). Refused, with nothing posted, when the target is no
    /// longer frontmost, Sabbel is frontmost or the focused field is a password
    /// field. Returns whether Return was pressed.
    public func pressReturn(target: FocusTarget?, settle: TimeInterval = 0) -> Bool {
        if settle > 0 { env.sleep(settle) }
        guard focusTargetIsActive(target), !sabbelIsFrontmost() else {
            info("Send command: focus changed — Return not pressed")
            return false
        }
        if Self.isSecure(env.focusedElement()) {
            info("Send command: secure text field — Return not pressed")
            return false
        }
        // A still-held Option would turn Return into Option+Return.
        waitForModifiersReleased(timeout: modifierTimeout)
        env.postReturn(to: target?.pid)
        return true
    }

    // MARK: focus tracking

    /// True if Sabbel's own app is frontmost. A take with no target (it started
    /// in Sabbel's panel) would otherwise paste optimistically into Sabbel, where
    /// Cmd+V lands nowhere and the restored clipboard loses the dictation.
    func sabbelIsFrontmost() -> Bool {
        guard let ownPID else { return false }
        return env.frontmostPID() == ownPID
    }

    /// True if `target` is still frontmost.
    ///
    /// True when there's nothing to compare against — we stay optimistic and
    /// paste rather than silently dropping the user's dictation.
    func focusTargetIsActive(_ target: FocusTarget?) -> Bool {
        guard let target else { return true }
        guard let pid = env.frontmostPID() else { return true }
        return pid == target.pid
    }

    /// True if the focused element is a password field.
    ///
    /// Pasting a transcript there would leave it sitting in the clipboard (and in
    /// the history log), so we refuse outright.
    public static func isSecure(_ element: FocusedElement?) -> Bool {
        guard let subrole = element?.subrole, !subrole.isEmpty else { return false }
        return subrole.lowercased().contains("secure")
    }

    /// Check if the focused element likely accepts text input.
    ///
    /// Returns true (optimistic) when:
    /// - the AX query fails entirely (Electron apps, etc.) — assume paste works
    /// - the focused element has AXSelectedTextRange (has a cursor)
    /// - AXValue or AXSelectedText is settable
    /// - the role is not in the known non-text-input list
    ///
    /// Returns false only when we're confident there's no text input.
    static func canAcceptPaste(_ focused: FocusedElement?) -> Bool {
        guard let focused else {
            // Can't read focused element (Electron apps, etc.)
            // Be optimistic — Cmd+V usually works in these apps
            return true
        }
        // Check 1: does it have a text selection range? (most reliable positive signal)
        if focused.hasSelectedTextRange { return true }
        // Check 2: is AXValue or AXSelectedText settable?
        if focused.valueSettable || focused.selectedTextSettable { return true }
        // Check 3: is the role a known non-text role?
        if let role = focused.role, nonTextRoles.contains(role) { return false }
        // Unknown situation — be optimistic
        return true
    }

    /// Block until no modifier keys are physically held, or `timeout` elapses.
    ///
    /// Sabbel pastes the moment the hotkey is released, but the user's hand is
    /// still leaving the keyboard. If Option (or anything else) is still down when
    /// we post Cmd+V, the target app sees Cmd+Opt+V: the paste silently does
    /// nothing, or fires some unrelated shortcut.
    ///
    /// Returns true if the modifiers cleared, false on timeout (the caller pastes
    /// anyway rather than dropping the transcription).
    @discardableResult
    func waitForModifiersReleased(timeout: TimeInterval, poll: TimeInterval = Injector.modifierPoll) -> Bool {
        let deadline = env.now() + timeout
        while env.now() < deadline {
            if !env.modifiersHeld() { return true }
            env.sleep(poll)
        }
        info("Modifiers still held after \(String(format: "%.1f", timeout))s — pasting anyway")
        return false
    }

    // MARK: paste verification

    /// Flatten a field's text so a substring check survives how apps expose it.
    ///
    /// iTerm2 publishes the terminal grid as AXValue with NUL bytes between cells,
    /// so a pasted "Hallo Welt" reads back as "Hallo\0Welt" and a literal substring
    /// test can never match. Terminals also hard-wrap, which injects line breaks
    /// mid-string.
    public static func normalizeForMatch(_ text: String) -> String {
        text.split(whereSeparator: isSeparator).joined(separator: " ")
    }

    /// NUL plus what Python's `str.split()` treats as whitespace: Unicode
    /// White_Space and the ASCII information separators U+001C...U+001F.
    private static func isSeparator(_ c: Character) -> Bool {
        if c.isWhitespace { return true }
        guard c.unicodeScalars.count == 1, let v = c.unicodeScalars.first?.value else { return false }
        return v == 0 || (0x1C...0x1F).contains(v)
    }

    /// Did the focused field react to our paste?
    ///
    /// This decides *when* it is safe to put the user's clipboard back, not
    /// whether the paste succeeded — no AX signal is reliable enough for that
    /// verdict. A field that merely changed counts: restoring a moment early is
    /// the old behaviour, whereas claiming failure on a successful paste is a lie
    /// the user acts on.
    func pasteObserved(before: String?, expected: String) -> Bool {
        guard let value = env.focusedValue() else { return false }
        let needle = Self.normalizeForMatch(expected)
        // An empty needle matches anything, as Python's `"" in s` does.
        if needle.isEmpty || Self.normalizeForMatch(value).contains(needle) { return true }
        return before != nil && value != before
    }
}
