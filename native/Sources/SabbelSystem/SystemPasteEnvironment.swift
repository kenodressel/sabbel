import AppKit
import ApplicationServices
import CoreGraphics
import SabbelCore

/// `PasteEnvironment` bound to AppKit, Accessibility and Quartz.
public final class SystemPasteEnvironment: PasteEnvironment, @unchecked Sendable {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    // MARK: Accessibility

    public func frontmostPID() -> Int32? {
        NSWorkspace.shared.frontmostApplication?.processIdentifier
    }

    /// Bounded like `SystemFocusProbe`: the paste path reads the focused
    /// element several times per take (and polls its value), and an app that
    /// hangs would otherwise hold each read for AX's default 6 s.
    private func focusedUIElement() -> AXUIElement? {
        guard let pid = frontmostPID() else { return nil }
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, SystemFocusProbe.axTimeout)
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString, &value) == .success,
              let value, CFGetTypeID(value) == AXUIElementGetTypeID() else { return nil }
        let element = value as! AXUIElement
        AXUIElementSetMessagingTimeout(element, SystemFocusProbe.axTimeout)
        return element
    }

    private func stringAttribute(_ element: AXUIElement, _ name: String) -> String? {
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, name as CFString, &value) == .success else { return nil }
        return value as? String
    }

    private func isSettable(_ element: AXUIElement, _ name: String) -> Bool {
        var settable: DarwinBoolean = false
        return AXUIElementIsAttributeSettable(element, name as CFString, &settable) == .success && settable.boolValue
    }

    public func focusedElement() -> FocusedElement? {
        guard let element = focusedUIElement() else { return nil }
        var range: CFTypeRef?
        let hasRange = AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, &range) == .success
        return FocusedElement(
            role: stringAttribute(element, kAXRoleAttribute),
            subrole: stringAttribute(element, kAXSubroleAttribute),
            hasSelectedTextRange: hasRange,
            valueSettable: isSettable(element, kAXValueAttribute),
            selectedTextSettable: isSettable(element, kAXSelectedTextAttribute))
    }

    public func focusedValue() -> String? {
        guard let element = focusedUIElement() else { return nil }
        var value: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString, &value) == .success,
              let value else { return nil }
        // Python's str(value) for non-string values.
        return (value as? String) ?? String(describing: value)
    }

    // MARK: modifiers

    public func modifiersHeld() -> Bool {
        let mask: CGEventFlags = [.maskCommand, .maskControl, .maskAlternate, .maskShift, .maskSecondaryFn]
        return !CGEventSource.flagsState(.combinedSessionState).intersection(mask).isEmpty
    }

    // MARK: pasteboard

    public func captureClipboard() -> ClipboardSnapshot {
        let items = (pasteboard.pasteboardItems ?? []).map { item -> [PasteboardFlavor] in
            item.types.compactMap { type in item.data(forType: type).map { PasteboardFlavor(type.rawValue, $0) } }
        }
        return ClipboardSnapshot(items: items)
    }

    public func restoreClipboard(_ snapshot: ClipboardSnapshot) {
        pasteboard.clearContents()
        guard !snapshot.items.isEmpty else { return }
        let items = snapshot.items.map { flavors -> NSPasteboardItem in
            let item = NSPasteboardItem()
            // In the captured order: it is the item's fidelity order.
            for flavor in flavors { item.setData(flavor.data, forType: NSPasteboard.PasteboardType(flavor.type)) }
            return item
        }
        pasteboard.writeObjects(items)
    }

    public func writeTransient(_ text: String) -> Int {
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        item.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }

    public func clipboardChangeCount() -> Int { pasteboard.changeCount }

    public func clipboardString() -> String? { pasteboard.string(forType: .string) }

    // MARK: events

    public func postCommandV(to pid: Int32?) { postKey(9, flags: .maskCommand, to: pid) }

    public func postReturn(to pid: Int32?) { postKey(36, flags: [], to: pid) }

    private func postKey(_ virtualKey: CGKeyCode, flags: CGEventFlags, to pid: Int32?) {
        let source = CGEventSource(stateID: .hidSystemState)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: virtualKey, keyDown: false) else { return }
        down.flags = flags
        up.flags = flags
        if let pid {
            down.postToPid(pid)
            Thread.sleep(forTimeInterval: 0.01)
            up.postToPid(pid)
        } else {
            down.post(tap: .cgAnnotatedSessionEventTap)
            up.post(tap: .cgAnnotatedSessionEventTap)
        }
    }

    public func sleep(_ seconds: TimeInterval) { Thread.sleep(forTimeInterval: seconds) }

    public func now() -> TimeInterval { ProcessInfo.processInfo.systemUptime }
}
