import AppKit
import Testing
import SabbelCore
@testable import SabbelSystem

@Suite struct PasteboardTests {
    private func withBoard(_ body: (NSPasteboard, SystemPasteEnvironment) -> Void) {
        let board = NSPasteboard(name: .init("sabbel-test-\(UUID())"))
        defer { board.releaseGlobally() }
        body(board, SystemPasteEnvironment(pasteboard: board))
    }

    private let custom = NSPasteboard.PasteboardType("com.sabbel.test.custom")

    @Test func captureKeepsEveryType() {
        withBoard { board, env in
            let item = NSPasteboardItem()
            let str = Data("hello".utf8), rtf = Data("{\\rtf1 hi}".utf8), cus = Data([1, 2, 3])
            item.setData(str, forType: .string)
            item.setData(rtf, forType: .rtf)
            item.setData(cus, forType: custom)
            board.clearContents()
            #expect(board.writeObjects([item]))
            let snap = env.captureClipboard()
            #expect(snap.items.count == 1)
            #expect(snap.items[0].data(for: NSPasteboard.PasteboardType.string.rawValue) == str)
            #expect(snap.items[0].data(for: NSPasteboard.PasteboardType.rtf.rawValue) == rtf)
            #expect(snap.items[0].data(for: custom.rawValue) == cus)
        }
    }

    @Test func captureHandlesEmpty() {
        withBoard { board, env in
            board.clearContents()
            #expect(env.captureClipboard().items.isEmpty)
        }
    }

    @Test func restoreRewritesAllItems() {
        withBoard { board, env in
            let a = NSPasteboardItem(), b = NSPasteboardItem()
            a.setString("one", forType: .string)
            b.setString("two", forType: .string)
            b.setData(Data([9]), forType: custom)
            board.clearContents()
            board.writeObjects([a, b])
            let snap = env.captureClipboard()
            board.clearContents()
            board.setString("junk", forType: .string)
            env.restoreClipboard(snap)
            let again = env.captureClipboard()
            #expect(again.items == snap.items)
            #expect(again.items.count == 2)
        }
    }

    /// An item's types are in fidelity order, richest first, and apps paste the
    /// first type they understand. A restore that shuffles them can turn a rich
    /// paste into plain text.
    @Test func restorePreservesTypeOrder() {
        withBoard { board, env in
            let item = NSPasteboardItem()
            let types: [NSPasteboard.PasteboardType] = [
                custom, .rtf, .html, .string, .tiff, .png, NSPasteboard.PasteboardType("com.sabbel.test.other"),
            ]
            for (i, type) in types.enumerated() { item.setData(Data([UInt8(i)]), forType: type) }
            board.clearContents()
            board.writeObjects([item])
            // Whatever order the pasteboard settled on (it adds a UTF-16 flavour of
            // the string and moves it), a capture and restore must keep it.
            let before = board.pasteboardItems?.first?.types ?? []
            #expect(before.count >= types.count)

            env.restoreClipboard(env.captureClipboard())
            #expect(board.pasteboardItems?.first?.types == before)
        }
    }

    @Test func restoreEmptySnapshotJustClears() {
        withBoard { board, env in
            board.clearContents()
            board.setString("junk", forType: .string)
            env.restoreClipboard(ClipboardSnapshot(items: []))
            #expect(board.pasteboardItems?.isEmpty ?? true)
            #expect(env.clipboardString() == nil)
        }
    }

    @Test func writeTransientMarksItem() {
        withBoard { board, env in
            let before = env.clipboardChangeCount()
            let count = env.writeTransient("secret text")
            #expect(count > before)
            #expect(count == env.clipboardChangeCount())
            #expect(env.clipboardString() == "secret text")
            let types = Set(board.pasteboardItems?.first?.types.map(\.rawValue) ?? [])
            #expect(types.contains("org.nspasteboard.TransientType"))
            #expect(types.contains("org.nspasteboard.AutoGeneratedType"))
            #expect(!types.contains("org.nspasteboard.ConcealedType"))
        }
    }
}
